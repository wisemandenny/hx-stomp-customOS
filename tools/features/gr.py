"""The gain-reduction meter on the Home screen and a compressor's Edit view (src/m4/gr_meter.s), set by each compressor block's own
Mtr knobs (tools/patch_comp.py).

No Global Settings: the knobs live in the blocks. The DSP side (src/sharc/frame_probe.asm) goes in with them, and NAM keeps two blocks."""
FLAG = 'HX_GR'
ORDER = 90                          # before the breathing line, which reads SHOWN
MODULE = 'src/m4/gr_meter.s'
SHOWN = 20                          # data + 20 in the module: nonzero while the meter shows

RX_CB_LIT, RX_CB = 0x28da6134, 0x10001095                   # the receive callback of the DSP stream (frames of 256 words)
HOME_CTOR_CALL, HOME_CTOR = 0x28d96c44, 0x28dc91d0          # bl to the Home view's constructor at boot
HOME_PAINT_LIT, HOME_PAINT = 0x28d96e28, 0x28dc8d39         # the Home view's paint function, as registered
EDIT_PAINT_LIT, EDIT_PAINT = 0x28d96da0, 0x28dc27f9         # the Edit view top half's paint (list B), shared with dsp_meter
VIEW_PAINT_LIT, VIEW_PAINT = 0x28d96e38, 0x28d947c9         # the generic list A paint: the Edit view's bottom half and nine others


def comp_names(e3):
    """The Entry 3 string index of each metered compressor model's name: a block object's model, as the M4 keeps it."""
    import patch_comp as pc
    index = pc.e3_strings(e3)[3]
    return [index[name] for name, _ in pc.COMP_MODELS]


def inc(names):
    """gr.inc: the compressor models the Edit view shows the meter for."""
    return {'gr.inc': '@ gr.inc - generated by tools/features/gr.py from the stock Entry 3\n'
                      f'.equ COMP_COUNT, {len(names)}\n.macro COMP_NAMES\n    .hword {", ".join(map(str, names))}\n.endm\n'}


def apply(p):
    m = p.module(MODULE, inc(comp_names(p.load(3))))
    p.chain_ptr(RX_CB_LIT, RX_CB, before=m['frame'])
    p.chain_bl(HOME_CTOR_CALL, HOME_CTOR, after=m['construct'])
    p.chain_ptr(HOME_PAINT_LIT, HOME_PAINT, before=m['erase'], after=m['draw'])
    p.chain_ptr(EDIT_PAINT_LIT, EDIT_PAINT, after=m['edit_top'])
    p.chain_ptr(VIEW_PAINT_LIT, VIEW_PAINT, after=m['edit_params'])
